#!/usr/bin/env python3
"""Produce one reviewable ES module for the Cloudflare dashboard editor."""
from pathlib import Path
import re
root = Path(__file__).resolve().parents[1]
voice = (root / 'cloudflare-worker/src/voice.js').read_text()
voice = re.sub(r'^export ', '', voice, flags=re.MULTILINE)
main = (root / 'cloudflare-worker/src/index.js').read_text().replace('import { handleVoice } from "./voice.js";\n', '', 1)
out = root / 'cloudflare-worker/dist/worker-voice.mjs'
out.parent.mkdir(exist_ok=True)
out.write_text('// Generated by scripts/bundle_voice_worker.py. No secrets included.\nconst handleVoice = (() => {\n' + voice + '\nreturn handleVoice;\n})();\n' + main)
print(out)
